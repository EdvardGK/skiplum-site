function wallCharHeight(h){ return Math.min(0.40, h*0.16); }
function wallBandZs(zBot, height, n, top=0.80, bot=0.20){
  if(n<=0) return [];
  if(n===1) return [zBot + height*(top+bot)/2];
  const out=[]; for(let i=0;i<n;i++) out.push(zBot + height*(top-(top-bot)*i/(n-1))); return out;
}

// Yields voxel specs {bx,by,z,tx,ty,rx,ry,ht,hr,hv} for text wrapped on a cylinder wall.
function voxelsOnCylinder(cx,cy,zCenter,text,radius,charHeight,voxelDepth,faceCompassDeg){
  const specs=[]; text=(text||"").toUpperCase(); if(!text) return specs;
  const voxel=charHeight/7, charW=5*voxel, pitch=charW+voxel;
  const totalArc=text.length*pitch;
  const centerAngle=(90-faceCompassDeg)*Math.PI/180;
  const startAngle=centerAngle-totalArc/(2*radius);
  const ht=voxel/2, hr=voxelDepth/2, hv=voxel/2;
  for(let ci=0;ci<text.length;ci++){
    const pat=FONT[text[ci]]||FONT[" "];
    const charLeft=startAngle+(ci*pitch)/radius;
    for(let row=0;row<7;row++) for(let col=0;col<5;col++){
      if(pat[row][col]!=="1") continue;
      const a=charLeft+((col+0.5)*voxel)/radius;
      const z=zCenter+(3-row)*voxel;
      const ca=Math.cos(a), sa=Math.sin(a);
      specs.push({bx:cx+radius*ca, by:cy+radius*sa, z:z, tx:-sa, ty:ca, rx:ca, ry:sa, ht:ht, hr:hr, hv:hv});
    }
  }
  return specs;
}

// All wall text for one marker at origin (top label + 3 rows), matching the builder.
window.markerTextSpecs = function(cfg){
  const R=cfg.diameter_m/2 + (cfg.wall_thickness_m||0), h=cfg.height_m;  // outer radius
  const lines=[cfg.text.top_label, cfg.text.row1, cfg.text.row2, cfg.text.row3].filter(s=>s && s.trim());
  const wch=wallCharHeight(h), zs=wallBandZs(0,h,lines.length);
  let specs=[];
  lines.forEach((line,i)=>{ specs=specs.concat(voxelsOnCylinder(0,0,zs[i],line,R+0.02,wch,0.04,180)); });
  return specs;
};
